//! Omarchy-style per-app theme file generators and legacy `appearance.json` compatibility.

use crate::{
    ActiveTheme, Appearance, SCHEMA_VERSION,
    color::{hex, hex_bare},
};
use serde::{Deserialize, Serialize};
use std::fmt::Write as _;

/// Backwards-compatible `appearance.json` payload matching `apps/studio-settings`
/// (`#[serde(deny_unknown_fields)]`, schema version 1).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct LegacyAppearance {
    pub schema_version: u32,
    pub theme: Appearance,
    #[serde(default = "default_legacy_wallpaper")]
    pub wallpaper: String,
    pub studio: bool,
    pub reduced_motion: bool,
}

fn default_legacy_wallpaper() -> String {
    "signal-feather".to_string()
}

impl Default for LegacyAppearance {
    fn default() -> Self {
        Self {
            schema_version: SCHEMA_VERSION,
            theme: Appearance::Dark,
            wallpaper: default_legacy_wallpaper(),
            studio: false,
            reduced_motion: true,
        }
    }
}

/// Map a background filename to one of the 3 legacy `appearance.json` wallpaper slugs, if it matches.
pub(crate) fn background_to_legacy_wallpaper(background: Option<&str>) -> Option<&'static str> {
    match background? {
        "signal-feather.png" | "wallpaper.png" => Some("signal-feather"),
        "nightwatch.png" => Some("nightwatch"),
        "quiet-signal.png" | "quiet-signal-4k.png" => Some("quiet-signal"),
        _ => None,
    }
}

/// Map a legacy `appearance.json` wallpaper slug to its canonical theme background filename.
pub(crate) fn legacy_wallpaper_to_background(wallpaper: &str) -> &'static str {
    match wallpaper {
        "nightwatch" => "nightwatch.png",
        "quiet-signal" => "quiet-signal.png",
        _ => "signal-feather.png",
    }
}

/// Map a legacy `appearance.json` `Appearance` value to its canonical built-in theme ID.
pub(crate) fn legacy_appearance_to_theme_id(appearance: Appearance) -> &'static str {
    match appearance {
        Appearance::Dark => "nullkeel-dark",
        Appearance::Light => "nullkeel-light",
        Appearance::WarmPaper => "warm-paper",
    }
}

/// Build a strict 5-field `appearance.json` struct synced from `active` while preserving
/// existing `reduced_motion` and fallback `wallpaper`.
pub(crate) fn build_legacy_appearance(active: &ActiveTheme, previous: Option<&LegacyAppearance>) -> LegacyAppearance {
    let prev_wallpaper = previous
        .map(|p| p.wallpaper.as_str())
        .filter(|w| matches!(*w, "signal-feather" | "nightwatch" | "quiet-signal"))
        .unwrap_or("signal-feather");
    let wallpaper = background_to_legacy_wallpaper(active.background.as_deref())
        .unwrap_or(prev_wallpaper)
        .to_string();
    let reduced_motion = previous.map(|p| p.reduced_motion).unwrap_or(true);

    LegacyAppearance {
        schema_version: SCHEMA_VERSION,
        theme: active.appearance,
        wallpaper,
        studio: active.studio,
        reduced_motion,
    }
}

/// Render `<xdg_config>/foot/theme.ini` for the Foot Wayland terminal.
pub fn render_foot_ini(active: &ActiveTheme) -> String {
    let c = &active.colors;
    let initial = if active.studio || active.appearance.is_dark() {
        "dark"
    } else {
        "light"
    };

    let mut body = String::with_capacity(640);
    let _ = writeln!(body, "background={}", hex_bare(c.canvas));
    let _ = writeln!(body, "foreground={}", hex_bare(c.text));
    let _ = writeln!(body, "cursor={} {}", hex_bare(c.on_accent), hex_bare(c.accent));
    let _ = writeln!(body, "selection-background={}", hex_bare(c.line));
    let _ = writeln!(body, "selection-foreground={}", hex_bare(c.text));
    let _ = writeln!(body, "urls={}", hex_bare(c.focus));
    for i in 0..8 {
        let _ = writeln!(body, "regular{i}={}", hex_bare(c.ansi[i]));
    }
    for i in 0..8 {
        let _ = writeln!(body, "bright{i}={}", hex_bare(c.ansi[i + 8]));
    }

    let mut out = String::with_capacity(1400);
    let _ = writeln!(
        out,
        "# Generated by CrowbarOS Theme Engine (theme: {})",
        active.theme_id
    );
    let _ = writeln!(out, "[main]");
    let _ = writeln!(out, "initial-color-theme={initial}");
    let _ = writeln!(out);
    let _ = writeln!(out, "[colors-dark]");
    out.push_str(&body);
    let _ = writeln!(out);
    let _ = writeln!(out, "[colors-light]");
    out.push_str(&body);
    out
}

/// Render `<xdg_config>/gtk-3.0/colors.css` and `<xdg_config>/gtk-4.0/colors.css`.
pub fn render_gtk_css(active: &ActiveTheme) -> String {
    let c = &active.colors;
    format!(
        "/* Generated by CrowbarOS Theme Engine (theme: {id}) */\n\
         @define-color window_bg_color {canvas};\n\
         @define-color window_fg_color {text};\n\
         @define-color view_bg_color {surface};\n\
         @define-color view_fg_color {text};\n\
         @define-color headerbar_bg_color {surface};\n\
         @define-color headerbar_fg_color {text};\n\
         @define-color accent_bg_color {accent};\n\
         @define-color accent_fg_color {on_accent};\n\
         @define-color accent_color {focus};\n\
         @define-color card_bg_color {surface_elevated};\n\
         @define-color card_fg_color {text};\n\
         @define-color popover_bg_color {surface_elevated};\n\
         @define-color popover_fg_color {text};\n\
         @define-color borders {line};\n\
         @define-color destructive_bg_color {danger};\n\
         @define-color warning_bg_color {warning};\n\
         @define-color success_bg_color {success};\n",
        id = active.theme_id,
        canvas = hex(c.canvas),
        surface = hex(c.surface),
        surface_elevated = hex(c.surface_elevated),
        text = hex(c.text),
        accent = hex(c.accent),
        on_accent = hex(c.on_accent),
        focus = hex(c.focus),
        line = hex(c.line),
        danger = hex(c.danger),
        warning = hex(c.warning),
        success = hex(c.success),
    )
}
