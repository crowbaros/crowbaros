//! Render the GRUB menu that lists every generation.
//!
//! The ESP carries a tiny standalone GRUB whose embedded config finds the
//! Btrfs filesystem by label and loads `/crowbar/grub.cfg` from its top level.
//! That file is regenerated from generation records on every apply/rollback.

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BootEntry {
    pub id: u32,
    pub title: String,
    /// Kernel path relative to the Btrfs top level, e.g. `/gens/2/boot/vmlinuz-6.18.63_1`.
    pub kernel: String,
    pub initrd: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MenuOptions {
    pub timeout_secs: u32,
    pub root_label: String,
    pub extra_cmdline: String,
}

impl Default for MenuOptions {
    fn default() -> Self {
        MenuOptions {
            timeout_secs: 10,
            root_label: "crowbar-root".into(),
            extra_cmdline: "console=tty0 console=ttyS0,115200".into(),
        }
    }
}

fn sanitize(title: &str) -> String {
    title
        .chars()
        .map(|c| if c.is_ascii_graphic() || c == ' ' { c } else { '?' })
        .filter(|c| !matches!(c, '"' | '\\' | '$' | '`'))
        .collect()
}

/// Entries are listed newest first; `default` selects the entry GRUB boots
/// when nobody touches the menu.
pub fn render_grub_cfg(entries: &[BootEntry], default: u32, opts: &MenuOptions) -> String {
    let mut sorted: Vec<&BootEntry> = entries.iter().collect();
    sorted.sort_by_key(|e| std::cmp::Reverse(e.id));
    let mut cfg = String::new();
    cfg.push_str("# Generated by crowbar from /crowbar/generations. Do not edit by hand.\n");
    cfg.push_str("insmod part_gpt\ninsmod btrfs\n");
    cfg.push_str("serial --unit=0 --speed=115200\n");
    cfg.push_str("terminal_input serial console\nterminal_output serial console\n");
    cfg.push_str(&format!("set timeout={}\n", opts.timeout_secs));
    cfg.push_str(&format!("set default=\"gen-{default}\"\n\n"));
    for entry in sorted {
        let marker = if entry.id == default { " [default]" } else { "" };
        cfg.push_str(&format!(
            "menuentry \"{}{}\" --id gen-{} {{\n",
            sanitize(&entry.title),
            marker,
            entry.id
        ));
        cfg.push_str(&format!(
            "    linux {} root=LABEL={} rootflags=subvol=gens/{} rw crowbar.generation={} {}\n",
            entry.kernel, opts.root_label, entry.id, entry.id, opts.extra_cmdline
        ));
        cfg.push_str(&format!("    initrd {}\n}}\n\n", entry.initrd));
    }
    cfg
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(id: u32) -> BootEntry {
        BootEntry {
            id,
            title: format!("CrowbarOS generation {id} \"quoted\" $x"),
            kernel: format!("/gens/{id}/boot/vmlinuz-6.18"),
            initrd: format!("/gens/{id}/boot/initramfs-6.18.img"),
        }
    }

    #[test]
    fn newest_first_with_default_marked() {
        let cfg = render_grub_cfg(&[entry(1), entry(3), entry(2)], 2, &MenuOptions::default());
        let p3 = cfg.find("--id gen-3").unwrap();
        let p2 = cfg.find("--id gen-2").unwrap();
        let p1 = cfg.find("--id gen-1").unwrap();
        assert!(p3 < p2 && p2 < p1);
        assert!(cfg.contains("set default=\"gen-2\""));
        assert!(cfg.contains("generation 2 quoted x [default]"));
        assert!(!cfg.contains("generation 3 quoted x [default]"));
        assert!(cfg.contains("rootflags=subvol=gens/3 rw crowbar.generation=3"));
        assert!(cfg.contains("initrd /gens/1/boot/initramfs-6.18.img"));
    }
}
