"""The person's synthetic Data: a home folder written fresh on every reset.

Text files come from seed/home with their {{class:ID}} placeholders expanded.
Photos and the archive are generated by code. Every file's modification time is
the lab epoch, so a listing is the same on every run.
"""
import json
import os
from pathlib import Path
import shutil
import struct

from fixtures import EPOCH, SEED, sha256

HOME_SEED = SEED / "home"


def exif(date):
    """An APP1 segment whose EXIF data holds DateTime and DateTimeOriginal."""
    stamp = date.encode("ascii") + b"\0"
    assert len(stamp) == 20, date
    # Big-endian TIFF: header, IFD0 (DateTime, ExifIFD pointer), Exif IFD
    # (DateTimeOriginal), then the two strings. Offsets count from the header.
    ifd0, exif_ifd, strings = 8, 8 + 2 + 2 * 12 + 4, 8 + 30 + 2 + 12 + 4
    tiff = b"MM\0*" + struct.pack(">I", ifd0)
    tiff += struct.pack(">H", 2)
    tiff += struct.pack(">HHII", 0x0132, 2, 20, strings)
    tiff += struct.pack(">HHII", 0x8769, 4, 1, exif_ifd)
    tiff += struct.pack(">I", 0)
    tiff += struct.pack(">H", 1)
    tiff += struct.pack(">HHII", 0x9003, 2, 20, strings + 20)
    tiff += struct.pack(">I", 0)
    tiff += stamp + stamp
    payload = b"Exif\0\0" + tiff
    return b"\xff\xe1" + struct.pack(">H", len(payload) + 2) + payload


def jpeg(date):
    """A valid 8x8 mid-grey baseline JPEG, with EXIF dates when date is set.
    The one block has a DC difference of 0 and no AC terms, so each Huffman
    table needs one code."""
    segment = lambda marker, body: marker + struct.pack(">H", len(body) + 2) + body
    out = b"\xff\xd8"
    if date:
        out += exif(date)
    out += segment(b"\xff\xdb", b"\x00" + bytes([1] * 64))                 # DQT
    out += segment(b"\xff\xc0", b"\x08" + struct.pack(">HH", 8, 8) + b"\x01\x01\x11\x00")  # SOF0
    out += segment(b"\xff\xc4", b"\x00" + bytes([1] + [0] * 15) + b"\x00")  # DHT, DC 0
    out += segment(b"\xff\xc4", b"\x10" + bytes([1] + [0] * 15) + b"\x00")  # DHT, AC 0
    out += segment(b"\xff\xda", b"\x01\x01\x00\x00\x3f\x00")               # SOS
    out += b"\x3f"  # DC category 0 ("0"), end of block ("0"), padded with ones.
    return out + b"\xff\xd9"


def write(dest, canaries):
    """Write the home folder to dest, replacing what is there. Returns the
    folder's digest."""
    spec = json.loads((SEED / "home.json").read_text())
    dest = Path(dest)
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for source in sorted(HOME_SEED.rglob("*")):
        if source.is_file():
            target = dest / source.relative_to(HOME_SEED)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(canaries.expand(source.read_text()))
    photos = dest / "Photos"
    photos.mkdir()
    for name, date in spec["photos"]["files"]:
        (photos / name).write_bytes(jpeg(date))
    archive = dest / spec["archive"]["dir"]
    archive.mkdir(parents=True)
    for n in range(1, spec["archive"]["count"] + 1):
        (archive / f"note-{n:03d}.txt").write_text(f"Note {n}. Nothing private here.\n")
    epoch = EPOCH.timestamp()
    for path in sorted(dest.rglob("*"), reverse=True):
        os.utime(path, (epoch, epoch))
    os.utime(dest, (epoch, epoch))
    return digest(dest)


def files(dest):
    dest = Path(dest)
    return sorted(str(p.relative_to(dest)) for p in dest.rglob("*") if p.is_file())


def digest(dest):
    """A digest over every file's path, content, and modification time."""
    dest = Path(dest)
    lines = [f"{name}\0{sha256((dest / name).read_bytes())}\0{int((dest / name).stat().st_mtime)}"
             for name in files(dest)]
    return sha256("\n".join(lines).encode())


def exif_date(data):
    """DateTimeOriginal from a JPEG this module wrote, or None."""
    marker = b"\x90\x03\x00\x02\x00\x00\x00\x14"
    at = data.find(marker)
    if at < 0 or not data.startswith(b"\xff\xd8\xff\xe1"):
        return None
    tiff = 4 + 2 + 6  # SOI, APP1 marker and length, "Exif\0\0"
    offset = struct.unpack(">I", data[at + 8:at + 12])[0]
    return data[tiff + offset:tiff + offset + 19].decode("ascii")
